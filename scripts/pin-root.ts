// Regenerates src/anchors.ts from a root CA certificate (DER). Only the public
// key, subject and certificate fingerprint are written; the certificate itself
// is not part of the package.
//
//   node scripts/pin-root.ts path/to/root.cer > src/anchors.ts
import { readFile } from "node:fs/promises";
import { parseCertificate } from "../src/x509.ts";

const path = process.argv[2];
if (!path) {
  console.error("usage: node scripts/pin-root.ts <root.cer>");
  process.exit(2);
}
const cert = await parseCertificate(new Uint8Array(await readFile(path)));
if (!cert.selfIssued) {
  console.error("not a self-issued (root) certificate");
  process.exit(1);
}
const b64 = Buffer.from(cert.spki.keyBytes).toString("base64");
const lines = b64.match(/.{1,76}/g) ?? [];
process.stdout.write(`// Generated by scripts/pin-root.ts. Do not edit by hand.
//
// Pin of the Apple Prove root CA that anchors Reference Image certificate
// chains: its subject, the SHA-256 of its certificate, and its composite
// public key (ML-DSA-87 || RSAPublicKey). The certificate itself is not
// included; pass it via the \`trustAnchors\` option to also check its validity
// period and self-signature.
import { fromBase64 } from "./util.ts";

export interface PinnedRoot {
  subject: string;
  subjectCN: string;
  /** Uppercase hex SHA-256 of the root certificate DER. */
  certSha256: string;
  /** Signature / key algorithm OID. */
  algorithmOid: string;
  /** Composite SPKI key bytes: ML-DSA-87 public key || RSAPublicKey DER. */
  publicKey: Uint8Array;
}

export const APPLE_PROVE_ROOT: PinnedRoot = {
  subject: ${JSON.stringify(cert.subject.dn)},
  subjectCN: ${JSON.stringify(cert.subject.cn ?? "")},
  certSha256: ${JSON.stringify(cert.fingerprintSha256)},
  algorithmOid: ${JSON.stringify(cert.spki.algorithmOid)},
  publicKey: fromBase64(
${lines.map((l, i) => `    "${l}"${i < lines.length - 1 ? " +" : ","}`).join("\n")}
  ),
};
`);
