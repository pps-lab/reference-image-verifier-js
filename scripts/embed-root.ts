// Regenerates src/anchors.ts from a root CA certificate (DER): the certificate
// itself plus its subject, fingerprint and public key.
//
//   node scripts/embed-root.ts path/to/root.cer > src/anchors.ts
import { readFile } from "node:fs/promises";
import { parseCertificate } from "../src/x509.ts";

const path = process.argv[2];
if (!path) {
  console.error("usage: node scripts/embed-root.ts <root.cer>");
  process.exit(2);
}
const cert = await parseCertificate(new Uint8Array(await readFile(path)));
if (!cert.selfIssued) {
  console.error("not a self-issued (root) certificate");
  process.exit(1);
}
const b64Lines = (bytes: Uint8Array): string => {
  const lines =
    Buffer.from(bytes)
      .toString("base64")
      .match(/.{1,76}/g) ?? [];
  return lines
    .map((l, i) => `    "${l}"${i < lines.length - 1 ? " +" : ","}`)
    .join("\n");
};
process.stdout
  .write(`// Generated by scripts/embed-root.ts. Do not edit by hand.
//
// The Apple Prove root CA that anchors Reference Image certificate chains.
// Every field other than \`der\` is derived from \`der\`.
import { fromBase64 } from "./util.ts";

export interface PinnedRoot {
  subject: string;
  subjectCN: string;
  /** Uppercase hex SHA-256 of the root certificate DER. */
  certSha256: string;
  /** Signature / key algorithm OID. */
  algorithmOid: string;
  /** Composite SPKI key bytes: ML-DSA-87 public key || RSAPublicKey DER. */
  publicKey: Uint8Array;
  /** The root certificate, DER. */
  der: Uint8Array;
}

export const APPLE_PROVE_ROOT: PinnedRoot = {
  subject: ${JSON.stringify(cert.subject.dn)},
  subjectCN: ${JSON.stringify(cert.subject.cn ?? "")},
  certSha256: ${JSON.stringify(cert.fingerprintSha256)},
  algorithmOid: ${JSON.stringify(cert.spki.algorithmOid)},
  publicKey: fromBase64(
${b64Lines(cert.spki.keyBytes)}
  ),
  der: fromBase64(
${b64Lines(cert.der)}
  ),
};
`);
